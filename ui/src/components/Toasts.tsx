import { useBoard } from '../state/BoardContext';

export function Toasts() {
  const { toasts } = useBoard();
  return (
    <div className="toasts" aria-live="polite">
      {toasts.map((t) => (
        <div key={t.id} className={`toast ${t.kind}`}>
          {t.text}
        </div>
      ))}
    </div>
  );
}
